const { contextBridge, ipcRenderer } = require('electron');
const subscribe = (channel, read) => callback => {
  const listener = (_event, value) => callback(read(value));
  ipcRenderer.on(channel, listener);
  return () => ipcRenderer.removeListener(channel, listener);
};
contextBridge.exposeInMainWorld('companion', {
  regions: value => ipcRenderer.send('regions', value),
  dragging: value => ipcRenderer.send('dragging', value),
  hover: value => ipcRenderer.send('hover', value),
  minimize: () => ipcRenderer.send('minimize'),
  quit: () => ipcRenderer.send('quit'),
  onAdded: subscribe('added', value => value),
  onClear: subscribe('clear-chibis', () => undefined),
  // Only the known boolean modes cross the bridge.
  onSettings: subscribe('settings', value => ({
    alwaysOnTop: value?.alwaysOnTop === true,
    followSpaces: value?.followSpaces !== false,
    clickChibis: value?.clickChibis === true,
    walkHorizontal: value?.walkHorizontal !== false,
    walkVertical: value?.walkVertical === true,
    lockToScreen: value?.lockToScreen !== false,
    rememberChibis: value?.rememberChibis !== false,
    fpsLimit: [15,30,60].includes(value?.fpsLimit) ? value.fpsLimit : 60,
    launchAtLogin: value?.launchAtLogin === true,
    gravity: value?.gravity === true,
    windowEdges: value?.windowEdges === true,
  })),
  onDisplays: subscribe('displays', value => Array.isArray(value) ? value : []),
  requestDisplays: () => ipcRenderer.send('get-displays'),
  requestSettings: () => ipcRenderer.send('get-settings'),
  addChibi: entry => ipcRenderer.send('add-chibi', entry),
  clearChibis: () => ipcRenderer.send('clear-chibis'),
  reportCount: count => ipcRenderer.send('count', count),
  onCount: subscribe('count', value => Number(value) || 0),
  requestCount: () => ipcRenderer.send('get-count'),
  saveChibis: ids => ipcRenderer.send('chibis-changed', ids),
  getChibis: () => ipcRenderer.send('get-chibis'),
  onChibis: subscribe('chibis', value => Array.isArray(value) ? value.filter(id => typeof id === 'string') : []),
  setSetting: (key, value) => ipcRenderer.send('set-setting', key, value),
  requestServices: () => ipcRenderer.send('get-services'),
  requestSurfaces: () => ipcRenderer.send('get-surfaces'),
  onSurfaces: subscribe('surfaces',value=>Array.isArray(value)?value:[]),
  onServices: subscribe('services',value=>value),
  requestLibrary: () => ipcRenderer.send('get-library'),
  onLibrary: subscribe('library',value=>value),
  downloadModels: ids => ipcRenderer.send('library-download',ids),
  importModels: () => ipcRenderer.send('library-import'),
  exportModels: () => ipcRenderer.send('library-export'),
  clearDownloads: () => ipcRenderer.send('library-clear'),
  removePack: id => ipcRenderer.send('library-remove',id),
  requestUpdates: () => ipcRenderer.send('get-updates'),
  onUpdates: subscribe('updates',value=>value),
  updateAction: action => ipcRenderer.send('update-action',action),
});
